#!/usr/bin/env bash
# Build the fixture workspace used by the repos script tests.
#
# Usage: scripts/test/build-fixture.sh <workspace-dir>
#
# Creates <workspace-dir>/root (a copy of scripts/ plus a generated repos.txt) and
# <workspace-dir>/remotes (local bare repositories). The manifest lists four entries:
#   alpha    a normal repository, cloned and pulled without problems
#   bravo    a normal repository that the runner changes locally after cloning
#   charlie  a folder that already exists and is not a Git repository
#   delta    a URL that cannot be reached
set -euo pipefail

if [ $# -ne 1 ]; then
    echo "Usage: $0 <workspace-dir>" >&2
    exit 2
fi

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
scripts_dir="$(dirname "$here")"
mkdir -p "$1"
ws="$(cd "$1" && { pwd -W 2>/dev/null || pwd; })"

export GIT_AUTHOR_NAME=fixture GIT_AUTHOR_EMAIL=fixture@example.invalid
export GIT_COMMITTER_NAME=fixture GIT_COMMITTER_EMAIL=fixture@example.invalid

mkdir -p "$ws/root/scripts" "$ws/remotes"
cp "$scripts_dir/repos.sh" "$scripts_dir/repos.ps1" "$ws/root/scripts/"

for name in alpha bravo; do
    git init --quiet --bare --initial-branch=main "$ws/remotes/$name.git"
    seed="$ws/seed-$name"
    git init --quiet --initial-branch=main "$seed"
    git -C "$seed" config core.autocrlf false
    echo "$name" > "$seed/README.md"
    git -C "$seed" add README.md
    git -C "$seed" -c commit.gpgsign=false commit --quiet -m "Initial commit"
    git -C "$seed" push --quiet "$ws/remotes/$name.git" main
done

mkdir -p "$ws/root/charlie"
echo "not a repository" > "$ws/root/charlie/notes.txt"

cat > "$ws/root/repos.txt" <<MANIFEST
# Fixture manifest generated by scripts/test/build-fixture.sh.
alpha    $ws/remotes/alpha.git      main
bravo    $ws/remotes/bravo.git      main

charlie  $ws/remotes/charlie.git    main
delta    $ws/remotes/missing.git    main
MANIFEST
